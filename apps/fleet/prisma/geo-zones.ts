/** Inserts missing example zones by name; existing zones stay unchanged. */
export async function seedGeoZones(
  client: Pick<Prisma.TransactionClient, 'geoZone'>,
  scope: { tenantId: string; branchId: string },
): Promise<number> {
  const result = await client.geoZone.createMany({
    data: geoZoneSeeds.map(({ name, ring }) => ({
      ...scope,
      name,
      polygon: polygonJson(ring),
      ...ringBounds(ring),
    })),
    skipDuplicates: true,
  });
  return result.count;
}
