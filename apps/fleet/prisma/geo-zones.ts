/** Flat [longitude, latitude, longitude, latitude, ...] list as a ring. */
function pairs(values: number[]): Ring {
  const ring: Ring = [];
  for (let index = 0; index + 1 < values.length; index += 2) {
    ring.push([values[index] ?? 0, values[index + 1] ?? 0]);
  }
  return ring;
}

