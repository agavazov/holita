export function edataParameterLabel(parameterId: number) {
  const name = names.get(parameterId) ?? null;
  const suffix = name === null ? undefined : /\(([^()]*)\)$/.exec(name)?.[1];
  return { name, unit: suffix && units.has(suffix) ? suffix : null };
}
